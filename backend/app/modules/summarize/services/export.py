"""Render a Module 2 summary as a clean, editable .docx file."""

from __future__ import annotations

import io
from datetime import date
from typing import Any


def _text(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def _bullet_list(document: Any, items: list[Any]) -> None:
    for item in items:
        text = _text(item)
        if text:
            document.add_paragraph(text, style="List Bullet")


def summary_docx(summary: dict[str, Any]) -> bytes:
    """Build a Word document from a SummaryOut-shaped dictionary."""
    from docx import Document as DocxDocument
    from docx.shared import Inches, Pt

    source = summary.get("source") or {}
    title = _text(source.get("title")) or "Summary"
    citations = summary.get("citations") or {}
    mode = summary.get("mode") or "academic"
    detail = summary.get("detail") or "standard"
    ai_source = summary.get("ai_source") or "heuristic"

    document = DocxDocument()
    document.core_properties.title = title
    document.core_properties.author = "Scholaris"

    document.add_heading(title, level=1)

    meta_bits: list[str] = []
    authors = [name for name in (source.get("authors") or []) if _text(name)]
    if authors:
        meta_bits.append(", ".join(authors))
    if source.get("year"):
        meta_bits.append(str(source["year"]))
    if _text(source.get("journal")):
        meta_bits.append(_text(source.get("journal")))
    if meta_bits:
        document.add_paragraph(" · ".join(meta_bits))

    doi = _text(source.get("doi"))
    if doi:
        document.add_paragraph(f"https://doi.org/{doi}")

    tldr = _text(summary.get("tldr"))
    if tldr:
        document.add_heading("TL;DR", level=2)
        document.add_paragraph(tldr)

    sections = (
        ("Key points", summary.get("key_points") or []),
        ("Methods", summary.get("methods") or []),
        ("Findings", summary.get("findings") or []),
        ("Limitations", summary.get("limitations") or []),
    )
    for label, items in sections:
        if not items:
            continue
        document.add_heading(label, level=2)
        _bullet_list(document, items)

    quotes = summary.get("quotes") or []
    if quotes:
        document.add_heading("Verbatim quotes", level=2)
        for quote in quotes:
            text = _text(quote.get("text"))
            if not text:
                continue
            page = quote.get("page")
            suffix = f" (p. {page})" if page else ""
            paragraph = document.add_paragraph(f'"{text}"{suffix}')
            paragraph.paragraph_format.left_indent = Inches(0.35)

    reference = _text(citations.get("reference"))
    if reference:
        document.add_heading("APA reference", level=2)
        document.add_paragraph(reference)

    note = _text(citations.get("note"))
    if note:
        paragraph = document.add_paragraph(note)
        paragraph.runs[0].italic = True

    warnings = [text for text in (summary.get("warnings") or []) if _text(text)]
    if warnings:
        document.add_heading("Notes", level=2)
        _bullet_list(document, warnings)

    detail_label = {"quick": "quick read", "deep": "deep dive"}.get(detail, "standard")
    source_label = "AI summary" if ai_source == "llm" else "offline summary"
    mode_label = "plain-English mode" if mode == "plain" else "academic mode"
    footer = document.add_paragraph(
        f"Generated by Scholaris · {date.today().isoformat()} · "
        f"{source_label} · {detail_label} · {mode_label}"
    )
    for run in footer.runs:
        run.font.size = Pt(9)
        run.italic = True

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()
