import { useMemo, useRef, useState, type FormEvent } from "react";
import { Link, useLocation } from "react-router-dom";

import {
  downloadSummaryDocx,
  lookupDoi,
  saveSummary,
  summarizeDocx,
  summarizePdf,
  summarizeText,
} from "../../api/client";
import type {
  SaveSummaryResponse,
  Summary,
  SummaryDetail,
  SummaryMode,
  SummarySourceMeta,
} from "../../api/types";
import { Icon } from "../../components/Icon";
import { useLibrary } from "../library/LibraryContext";

type Mode = "text" | "pdf" | "docx";

interface MetaForm {
  title: string;
  authors: string;
  year: string;
  journal: string;
  doi: string;
  url: string;
}

interface SummarizeNavState {
  prefill?: {
    text?: string;
    title?: string;
    authors?: string[];
    year?: number | null;
    journal?: string | null;
    doi?: string | null;
    url?: string | null;
  };
  libraryId?: string | null;
}

const EMPTY_META: MetaForm = {
  title: "",
  authors: "",
  year: "",
  journal: "",
  doi: "",
  url: "",
};

const MAX_FILE_BYTES = 15 * 1024 * 1024;
const DOCX_MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";

function toMeta(form: MetaForm): SummarySourceMeta {
  const year = Number.parseInt(form.year, 10);
  return {
    title: form.title.trim(),
    authors: form.authors
      .split(",")
      .map((author) => author.trim())
      .filter(Boolean),
    year: Number.isFinite(year) ? year : null,
    journal: form.journal.trim() || null,
    doi: form.doi.trim() || null,
    url: form.url.trim() || null,
  };
}

function detailLabel(detail: SummaryDetail): string {
  if (detail === "quick") return "Quick read";
  if (detail === "deep") return "Deep dive";
  return "Standard depth";
}

function summaryToText(summary: Summary): string {
  const lines: string[] = [];
  if (summary.source.title) lines.push(summary.source.title, "");
  lines.push(`TL;DR: ${summary.tldr}`, "");

  const sections: Array<[string, string[], string]> = [
    ["Key points", summary.key_points, "None identified."],
    ["Methods", summary.methods, "The text does not describe the methods."],
    ["Findings", summary.findings, "The text does not report specific findings."],
    ["Limitations", summary.limitations, "The text does not state limitations."],
  ];
  for (const [label, items, empty] of sections) {
    lines.push(`${label}:`);
    lines.push(...(items.length > 0 ? items.map((item) => `- ${item}`) : [`- ${empty}`]));
    lines.push("");
  }

  if (summary.quotes.length > 0) {
    lines.push("Quotes:");
    for (const quote of summary.quotes) {
      lines.push(`- "${quote.text}"${quote.page ? ` (p. ${quote.page})` : ""}`);
    }
    lines.push("");
  }
  if (summary.citations.reference) {
    lines.push("APA 7 reference:", summary.citations.reference, "");
  }
  lines.push(
    `Generated by Scholaris · ${summary.ai_source === "llm" ? "AI summary" : "offline summary"}`,
  );
  return lines.join("\n");
}

export function SummarizePage() {
  const location = useLocation();
  const navState = (location.state as SummarizeNavState | null) ?? null;
  const prefill = navState?.prefill;
  const { notify, refresh } = useLibrary();
  const fileInput = useRef<HTMLInputElement>(null);

  const [mode, setMode] = useState<Mode>("text");
  const [text, setText] = useState(prefill?.text ?? "");
  const [meta, setMeta] = useState<MetaForm>(() => ({
    ...EMPTY_META,
    title: prefill?.title ?? "",
    authors: (prefill?.authors ?? []).join(", "),
    year: prefill?.year ? String(prefill.year) : "",
    journal: prefill?.journal ?? "",
    doi: prefill?.doi ?? "",
    url: prefill?.url ?? "",
  }));
  const [quoteCount, setQuoteCount] = useState(3);
  const [detail, setDetail] = useState<SummaryDetail>("standard");
  const [summaryMode, setSummaryMode] = useState<SummaryMode>("academic");
  const [file, setFile] = useState<File | null>(null);
  const [dragging, setDragging] = useState(false);
  const [loading, setLoading] = useState(false);
  const [doiLoading, setDoiLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [summary, setSummary] = useState<Summary | null>(null);
  const [saving, setSaving] = useState(false);
  const [saved, setSaved] = useState<SaveSummaryResponse | null>(null);

  // The stable Module 1 source id, when this summary was opened from a saved source.
  const [libraryId] = useState<string | null>(navState?.libraryId ?? null);

  const wordCount = useMemo(() => text.trim().split(/\s+/).filter(Boolean).length, [text]);
  const canSubmit =
    mode === "text" ? wordCount >= 25 && text.trim().length >= 80 : file !== null;
  const fileKind = mode === "pdf" ? "PDF" : "Word document";

  const updateMeta = (key: keyof MetaForm, value: string) => {
    setMeta((current) => ({ ...current, [key]: value }));
    setSaved(null);
  };

  const switchMode = (next: Mode) => {
    setMode(next);
    setFile(null);
    setDragging(false);
    setError(null);
    setSaved(null);
    if (fileInput.current) fileInput.current.value = "";
  };

  const chooseFile = (candidate: File | null) => {
    if (!candidate) {
      setFile(null);
      return;
    }
    const wantsPdf = mode === "pdf";
    const looksRight = wantsPdf
      ? candidate.type === "application/pdf" || candidate.name.toLowerCase().endsWith(".pdf")
      : candidate.type === DOCX_MIME || candidate.name.toLowerCase().endsWith(".docx");
    if (!looksRight) {
      setError(
        wantsPdf
          ? "Upload a .pdf file, or switch to “Paste text”."
          : "Upload a .docx file (Word or Google Docs export), or switch to “Paste text”.",
      );
      return;
    }
    if (candidate.size > MAX_FILE_BYTES) {
      setError(
        `That ${wantsPdf ? "PDF" : "Word document"} is larger than 15 MB. Try a smaller file or paste the text.`,
      );
      return;
    }
    setError(null);
    setFile(candidate);
    setSaved(null);
    if (!meta.title.trim()) {
      const guessed = candidate.name
        .replace(wantsPdf ? /\.pdf$/i : /\.docx$/i, "")
        .replace(/[_-]+/g, " ")
        .trim();
      if (guessed) updateMeta("title", guessed);
    }
  };

  const handleDoiLookup = async () => {
    const value = meta.doi.trim();
    if (!value || doiLoading) {
      if (!value) setError("Paste a DOI first, then fetch the details.");
      return;
    }
    setDoiLoading(true);
    setError(null);
    try {
      const record = await lookupDoi(value);
      setMeta((current) => ({
        ...current,
        title: record.title || current.title,
        authors: record.authors.length > 0 ? record.authors.join(", ") : current.authors,
        year: record.year ? String(record.year) : current.year,
        journal: record.journal ?? current.journal,
        doi: record.doi ?? current.doi,
        url: record.url ?? current.url,
      }));
      setSaved(null);
      notify("Details filled from the DOI record — check them before citing");
    } catch (caught) {
      setError(
        caught instanceof Error ? caught.message : "The DOI could not be looked up.",
      );
    } finally {
      setDoiLoading(false);
    }
  };

  const handleSubmit = async (event: FormEvent) => {
    event.preventDefault();
    if (!canSubmit || loading) return;

    setLoading(true);
    setError(null);
    setSaved(null);
    try {
      const source = toMeta(meta);
      let result: Summary;
      if (mode === "pdf" && file) {
        result = await summarizePdf(file, source, quoteCount, detail, summaryMode);
      } else if (mode === "docx" && file) {
        result = await summarizeDocx(file, source, quoteCount, detail, summaryMode);
      } else {
        result = await summarizeText({
          text,
          source,
          quote_count: quoteCount,
          detail,
          mode: summaryMode,
        });
      }
      setSummary(result);
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "The source could not be summarized.");
    } finally {
      setLoading(false);
    }
  };

  const handleSave = async () => {
    if (!summary || saving) return;
    setSaving(true);
    try {
      const result = await saveSummary(summary, libraryId);
      setSaved(result);
      await refresh();
      notify(result.message);
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "The summary could not be saved.");
    } finally {
      setSaving(false);
    }
  };

  const copyText = (value: string, message: string) => {
    void navigator.clipboard
      .writeText(value)
      .then(() => notify(message))
      .catch(() => notify("Your browser blocked the clipboard."));
  };

  const copySummary = async () => {
    if (!summary) return;
    try {
      await navigator.clipboard.writeText(summaryToText(summary));
      notify("Copied the whole summary");
    } catch {
      notify("Your browser blocked the clipboard. Download the .txt instead.");
    }
  };

  const downloadSummary = () => {
    if (!summary) return;
    const blob = new Blob([summaryToText(summary)], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    const today = new Date().toISOString().slice(0, 10);
    anchor.href = url;
    anchor.download = `scholaris-summary-${today}.txt`;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    URL.revokeObjectURL(url);
  };

  const downloadDocx = async () => {
    if (!summary || downloading) return;
    setDownloading(true);
    try {
      await downloadSummaryDocx(summary);
      notify("Downloaded the .docx summary");
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "The .docx could not be downloaded.");
    } finally {
      setDownloading(false);
    }
  };

  const apaForQuote = (page: number | null): string => {
    const citations = summary?.citations;
    if (!citations?.author_label) return "";
    const pagePart = page ? `, p. ${page}` : "";
    return `(${citations.author_label}, ${citations.year_label}${pagePart})`;
  };

  const reset = () => {
    setSummary(null);
    setSaved(null);
    setError(null);
    setText("");
    setFile(null);
    setMeta(EMPTY_META);
    setMode("text");
    if (fileInput.current) fileInput.current.value = "";
  };

  return (
    <section className="page">
      <header className="page-header">
        <p className="eyebrow">Module 2</p>
        <h1>Source Summarizer</h1>
        <p className="page-subtitle">
          Paste an abstract, upload a PDF or upload a Word document. Scholaris pulls out the key
          points, methods, findings and limitations — and keeps PDF quotes tied to their page
          numbers.
        </p>
      </header>

      <form className="card summarize-form" onSubmit={handleSubmit}>
        <div className="segmented" role="tablist" aria-label="Source type">
          <button
            type="button"
            role="tab"
            aria-selected={mode === "text"}
            className={`segment ${mode === "text" ? "segment-active" : ""}`}
            onClick={() => switchMode("text")}
          >
            <Icon name="summary" size={16} /> Paste text
          </button>
          <button
            type="button"
            role="tab"
            aria-selected={mode === "pdf"}
            className={`segment ${mode === "pdf" ? "segment-active" : ""}`}
            onClick={() => switchMode("pdf")}
          >
            <Icon name="upload" size={16} /> Upload PDF
          </button>
          <button
            type="button"
            role="tab"
            aria-selected={mode === "docx"}
            className={`segment ${mode === "docx" ? "segment-active" : ""}`}
            onClick={() => switchMode("docx")}
          >
            <Icon name="upload" size={16} /> Upload .docx
          </button>
        </div>

        {mode === "text" ? (
          <div className="field">
            <label htmlFor="source-text">Abstract, excerpt or full text</label>
            <textarea
              id="source-text"
              className="textarea source-textarea"
              value={text}
              onChange={(event) => {
                setText(event.target.value);
                setSaved(null);
              }}
              placeholder="Paste the abstract, introduction, results or the whole article here. At least a full abstract works best."
            />
            <div className="field-hint">
              <span>{wordCount.toLocaleString()} words</span>
              <span>Minimum 25 words</span>
            </div>
          </div>
        ) : (
          <div className="field">
            <span className="field-label">{fileKind} file</span>
            <label
              className={`dropzone ${dragging ? "dropzone-active" : ""} ${
                file ? "dropzone-ready" : ""
              }`}
              htmlFor={`source-file-${mode}`}
              onDragOver={(event) => {
                event.preventDefault();
                setDragging(true);
              }}
              onDragLeave={() => setDragging(false)}
              onDrop={(event) => {
                event.preventDefault();
                setDragging(false);
                chooseFile(event.dataTransfer.files?.[0] ?? null);
              }}
            >
              <input
                ref={fileInput}
                id={`source-file-${mode}`}
                className="file-input"
                type="file"
                accept={mode === "pdf" ? "application/pdf,.pdf" : `${DOCX_MIME},.docx`}
                onChange={(event) => chooseFile(event.target.files?.[0] ?? null)}
              />
              <span className="dropzone-icon">
                <Icon name={file ? "check" : "upload"} size={22} />
              </span>
              <span className="dropzone-title">
                {file
                  ? file.name
                  : `Drop a ${fileKind} here, or click to choose one`}
              </span>
              <span className="dropzone-hint">
                {file
                  ? mode === "pdf"
                    ? `${(file.size / 1024 / 1024).toFixed(1)} MB · quotes will keep page numbers`
                    : `${(file.size / 1024 / 1024).toFixed(1)} MB · page numbers appear when the file has page breaks`
                  : `Up to 15 MB. ${
                      mode === "pdf"
                        ? "Scanned PDFs without selectable text need OCR first."
                        : "In Word: File → Save As → Word Document (.docx). Old .doc files need converting first."
                    }`}
              </span>
            </label>
          </div>
        )}

        <details className="advanced">
          <summary>Source details (optional, used for citations and saving)</summary>
          <div className="advanced-body summary-meta-grid">
            <div className="field summary-meta-wide">
              <label htmlFor="meta-title">Title</label>
              <input
                id="meta-title"
                className="input"
                value={meta.title}
                placeholder="Full paper title"
                onChange={(event) => updateMeta("title", event.target.value)}
              />
            </div>
            <div className="field summary-meta-wide">
              <label htmlFor="meta-authors">Authors (comma separated)</label>
              <input
                id="meta-authors"
                className="input"
                value={meta.authors}
                placeholder="Ada Lovelace, Grace Hopper"
                onChange={(event) => updateMeta("authors", event.target.value)}
              />
            </div>
            <div className="field">
              <label htmlFor="meta-year">Year</label>
              <input
                id="meta-year"
                className="input"
                inputMode="numeric"
                value={meta.year}
                placeholder="2025"
                onChange={(event) => updateMeta("year", event.target.value)}
              />
            </div>
            <div className="field">
              <label htmlFor="meta-journal">Journal</label>
              <input
                id="meta-journal"
                className="input"
                value={meta.journal}
                placeholder="Journal name"
                onChange={(event) => updateMeta("journal", event.target.value)}
              />
            </div>
            <div className="field summary-meta-wide">
              <label htmlFor="meta-doi">DOI</label>
              <div className="doi-row">
                <input
                  id="meta-doi"
                  className="input"
                  value={meta.doi}
                  placeholder="10.1000/example"
                  onChange={(event) => updateMeta("doi", event.target.value)}
                />
                <button
                  type="button"
                  className="btn btn-small"
                  onClick={() => void handleDoiLookup()}
                  disabled={doiLoading || !meta.doi.trim()}
                >
                  {doiLoading ? "Looking up…" : "Fetch by DOI"}
                </button>
              </div>
              <span className="field-hint">Fills the title, authors, year and journal from OpenAlex.</span>
            </div>
            <div className="field">
              <label htmlFor="meta-url">URL</label>
              <input
                id="meta-url"
                className="input"
                value={meta.url}
                placeholder="https://…"
                onChange={(event) => updateMeta("url", event.target.value)}
              />
            </div>
          </div>
        </details>

        <div className="form-actions summarize-actions">
          <button type="submit" className="btn btn-primary btn-large" disabled={!canSubmit || loading}>
            <Icon name="summary" size={17} />
            {loading ? "Reading the source…" : "Summarize source"}
          </button>
          <label className="inline-select">
            Depth
            <select
              className="select select-inline"
              value={detail}
              onChange={(event) => setDetail(event.target.value as SummaryDetail)}
            >
              <option value="quick">Quick</option>
              <option value="standard">Standard</option>
              <option value="deep">Deep</option>
            </select>
          </label>
          <label className="inline-select">
            Style
            <select
              className="select select-inline"
              value={summaryMode}
              onChange={(event) => setSummaryMode(event.target.value as SummaryMode)}
            >
              <option value="academic">Academic</option>
              <option value="plain">Plain English</option>
            </select>
          </label>
          <label className="inline-select">
            Quotes
            <select
              className="select select-inline"
              value={quoteCount}
              onChange={(event) => setQuoteCount(Number(event.target.value))}
            >
              <option value={2}>2</option>
              <option value={3}>3</option>
              <option value={4}>4</option>
              <option value={5}>5</option>
            </select>
          </label>
          {summary ? (
            <button type="button" className="btn btn-ghost btn-small" onClick={reset}>
              Start over
            </button>
          ) : null}
        </div>
        <p className="faint summarize-privacy">
          When online AI is available, the text you paste is sent to your configured AI provider
          to write the summary. Without AI, the summary is built on this computer and nothing
          leaves it.
        </p>
      </form>

      {error ? <div className="banner banner-error">{error}</div> : null}

      {loading ? (
        <div className="card summary-loading">
          <span className="spinner" />
          <div>
            <strong>Finding the important parts…</strong>
            <p className="muted">
              This usually takes a few seconds. If the online AI is busy, Scholaris falls back
              to a careful offline summary.
            </p>
          </div>
        </div>
      ) : null}

      {summary ? (
        <article className="card summary-card">
          <header className="summary-head">
            <div>
              <div className="summary-badges">
                <span className={`badge ${summary.ai_source === "llm" ? "badge-good" : ""}`}>
                  {summary.ai_source === "llm" ? "AI summary" : "Offline summary"}
                </span>
                <span className="badge">{detailLabel(summary.detail)}</span>
                {summary.mode === "plain" ? <span className="badge">Plain English</span> : null}
                {summary.page_count ? (
                  <span className="badge">
                    {summary.page_count} page{summary.page_count === 1 ? "" : "s"}
                  </span>
                ) : null}
                <span className="badge">{summary.word_count.toLocaleString()} words read</span>
                <span className="badge">{(summary.took_ms / 1000).toFixed(1)}s</span>
              </div>
              <h2 className="summary-title">{summary.source.title}</h2>
              <p className="source-meta">
                {summary.source.authors.length > 0
                  ? summary.source.authors.slice(0, 4).join(", ")
                  : "Unknown authors"}
                {summary.source.authors.length > 4 ? ", et al." : ""} ·{" "}
                {summary.source.year ?? "n.d."}
                {summary.source.journal ? ` · ${summary.source.journal}` : ""}
              </p>
            </div>
          </header>

          {summary.warnings.length > 0 ? (
            <div className="banner banner-warn">
              <strong>Heads up</strong>
              <ul>
                {summary.warnings.map((warning) => (
                  <li key={warning}>{warning}</li>
                ))}
              </ul>
            </div>
          ) : null}

          <div className="summary-tldr">
            <span className="summary-label">
              <Icon name="logo" size={14} /> In plain English
            </span>
            <p>{summary.tldr}</p>
          </div>

          <div className="summary-grid">
            <SummarySection
              title="Key points"
              items={summary.key_points}
              empty="No main points were identified in this text."
            />
            <SummarySection
              title="Methods"
              items={summary.methods}
              empty="The provided text does not describe the methods."
            />
            <SummarySection
              title="Findings"
              items={summary.findings}
              empty="The provided text does not report specific findings."
            />
            <SummarySection
              title="Limitations"
              items={summary.limitations}
              empty="The provided text does not state limitations. Check the full paper's discussion."
            />
          </div>

          {summary.quotes.length > 0 ? (
            <section className="summary-quotes">
              <h3>
                <Icon name="quote" size={16} /> Verbatim quotes
                {summary.page_count ? " with page numbers" : ""}
              </h3>
              <div className="quote-list">
                {summary.quotes.map((quote, index) => (
                  <blockquote className="quote-card" key={`${index}-${quote.text.slice(0, 24)}`}>
                    <p>“{quote.text}”</p>
                    <footer>
                      <span className="badge">
                        {quote.page ? `Page ${quote.page}` : "From your text"}
                      </span>
                      {summary.citations.author_label ? (
                        <button
                          type="button"
                          className="icon-button quote-cite"
                          title="Copy APA 7 in-text citation"
                          aria-label="Copy APA 7 in-text citation"
                          onClick={() =>
                            copyText(apaForQuote(quote.page), "APA in-text citation copied")
                          }
                        >
                          APA
                        </button>
                      ) : null}
                      <button
                        type="button"
                        className="icon-button quote-copy"
                        aria-label="Copy this quote"
                        onClick={() => {
                          void navigator.clipboard
                            .writeText(
                              `"${quote.text}"${quote.page ? ` (p. ${quote.page})` : ""}`,
                            )
                            .then(() => notify("Quote copied"))
                            .catch(() => notify("Your browser blocked the clipboard."));
                        }}
                      >
                        <Icon name="copy" size={15} />
                      </button>
                    </footer>
                  </blockquote>
                ))}
              </div>
            </section>
          ) : null}

          {summary.citations.in_text || summary.citations.reference ? (
            <section className="summary-citation">
              <h3>
                <Icon name="quote" size={16} /> Cite this source (APA 7)
              </h3>
              {summary.citations.in_text ? (
                <div className="citation-line">
                  <span className="citation-label">In-text</span>
                  <code>{summary.citations.in_text}</code>
                  <button
                    type="button"
                    className="btn btn-ghost btn-small"
                    onClick={() => copyText(summary.citations.in_text, "APA in-text citation copied")}
                  >
                    Copy
                  </button>
                </div>
              ) : null}
              {summary.citations.narrative ? (
                <div className="citation-line">
                  <span className="citation-label">Narrative</span>
                  <code>{summary.citations.narrative}</code>
                  <button
                    type="button"
                    className="btn btn-ghost btn-small"
                    onClick={() => copyText(summary.citations.narrative, "APA narrative citation copied")}
                  >
                    Copy
                  </button>
                </div>
              ) : null}
              {summary.citations.reference ? (
                <div className="citation-reference">
                  <span className="citation-label">Reference</span>
                  <p>{summary.citations.reference}</p>
                  <button
                    type="button"
                    className="btn btn-ghost btn-small"
                    onClick={() => copyText(summary.citations.reference, "APA reference copied")}
                  >
                    <Icon name="copy" size={14} /> Copy reference
                  </button>
                </div>
              ) : null}
              {summary.citations.note ? <p className="faint">{summary.citations.note}</p> : null}
            </section>
          ) : summary.citations.note ? (
            <p className="faint">{summary.citations.note}</p>
          ) : null}

          <div className="card-actions summary-actions-row">
            <button
              type="button"
              className="btn btn-primary btn-small"
              disabled={saving || saved !== null}
              onClick={handleSave}
            >
              <Icon name={saved ? "check" : "plus"} size={15} />
              {saved
                ? "Saved"
                : saving
                  ? "Saving…"
                  : libraryId
                    ? "Add to saved source"
                    : "Save summary to library"}
            </button>
            <button type="button" className="btn btn-small" onClick={copySummary}>
              <Icon name="copy" size={15} /> Copy summary
            </button>
            <button type="button" className="btn btn-small" onClick={downloadSummary}>
              <Icon name="download" size={15} /> Download .txt
            </button>
            <button
              type="button"
              className="btn btn-small"
              onClick={() => void downloadDocx()}
              disabled={downloading}
            >
              <Icon name="download" size={15} />
              {downloading ? "Preparing…" : "Download .docx"}
            </button>
            {saved ? (
              <span className="faint">
                {saved.message} <Link to="/library">Open My Library</Link>
              </span>
            ) : summary.ai_source === "heuristic" ? (
              <span className="faint">
                Extracted word-for-word from your text — add a free AI key for a written
                summary.
              </span>
            ) : null}
          </div>
        </article>
      ) : null}

      {!summary && !loading ? (
        <div className="empty-state empty-hero">
          <div className="empty-hero-mark">
            <Icon name="summary" size={26} />
          </div>
          <h2>Turn a dense paper into something you can study</h2>
          <p className="muted">
            Every summary gives you a one-sentence overview, key points, methods, findings,
            limitations and ready-to-quote sentences. Saved summaries become notes in My
            Library, so your RRL and citations stay together.
          </p>
        </div>
      ) : null}
    </section>
  );
}

function SummarySection({
  title,
  items,
  empty,
}: {
  title: string;
  items: string[];
  empty: string;
}) {
  return (
    <section className="summary-section">
      <h3>{title}</h3>
      {items.length > 0 ? (
        <ul className="summary-list">
          {items.map((item, index) => (
            <li key={`${title}-${index}-${item.slice(0, 20)}`}>{item}</li>
          ))}
        </ul>
      ) : (
        <p className="muted summary-empty">{empty}</p>
      )}
    </section>
  );
}
